// テキスト中の【…】と {…} を黄色マーカーで表示する
function runs(text, opts = {}) {
  const parts = text.split(/(【[^】]*】|\{[^}]*\})/).filter(s => s !== '');
  return parts.map(p => {
    const mark = p.startsWith('【') || p.startsWith('{');
    const t = p.startsWith('{') ? p.slice(1, -1) : p;
    return new TextRun({ text: t, font: { eastAsia: FONT, ascii: FONT, hAnsi: FONT }, size: opts.size || 21, bold: opts.bold, highlight: mark ? 'yellow' : undefined });
  });
}
const P = (text, o = {}) => new Paragraph({ children: runs(text, o), alignment: o.align, spacing: { after: o.after ?? 80, line: 300 }, indent: o.indent ? { left: o.indent } : undefined });
const TITLE = t => new Paragraph({ children: runs(t, { size: 30, bold: true }), alignment: AlignmentType.CENTER, spacing: { after: 300 } });
const H = t => new Paragraph({ children: runs(t, { size: 23, bold: true }), spacing: { before: 200, after: 100 } });
const R = t => P(t, { align: AlignmentType.RIGHT });
const BL = () => new Paragraph({ children: [] });
const BREAK = () => new Paragraph({ children: [new PageBreak()] });

const border = { style: BorderStyle.SINGLE, size: 4, color: '666666' };
const borders = { top: border, bottom: border, left: border, right: border };
function table(rows, widths, header = true) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, i) => new TableRow({
      children: r.map((cell, j) => new TableCell({
        width: { size: widths[j], type: WidthType.DXA },
        borders,
        shading: header && i === 0 ? { type: ShadingType.CLEAR, color: 'auto', fill: 'E7E6E6' } : undefined,
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        children: String(cell).split('\n').map(l => new Paragraph({ children: runs(l, { size: 19, bold: header && i === 0 }) })),
      })),
    })),
  });
}
const NOTE = t => P('※' + t, { size: 18 });

async function save(file, children) {
  const doc = new Document({
    styles: { default: { document: { run: { font: { eastAsia: FONT, ascii: FONT, hAnsi: FONT }, size: 21 } } } },
    sections: [{ properties: { page: { margin: { top: 1300, bottom: 1200, left: 1300, right: 1300 } } }, children }],
  });
  fs.writeFileSync(path.join(OUT, file), await Packer.toBuffer(doc));
}

